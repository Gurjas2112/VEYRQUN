"""Automated test-case generation for the Rego policy.

Reads policies/data.schema.json, finds every field marked "x-boundary", and for each seeded agent
emits Rego tests at limit-0.01, limit and limit+0.01 (one minor unit). Expected outcomes come from
the independent Python oracle, not from the Rego under test.

Usage: python scripts/gen_policy_tests.py [--check]
--check fails if policies/veyrqun/generated_boundaries_test.rego is out of date (CI uses this).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "control-plane"))

from veyrqun.db import SEED_AGENTS  # noqa: E402
from veyrqun.money import to_minor  # noqa: E402
from veyrqun.policy.oracle import evaluate as oracle  # noqa: E402

SCHEMA = ROOT / "policies" / "data.schema.json"
OUT = ROOT / "policies" / "veyrqun" / "generated_boundaries_test.rego"


def seed_agent_docs() -> dict[str, dict]:
    docs = {}
    for a in SEED_AGENTS:
        docs[a["agent_key"]] = {
            "status": "active",
            "mode": "enforce",
            "policy_version": 1,
            "allowed_actions": a["allowed_actions"],
            "blocked_actions": a["blocked_actions"],
            "spend_cap_daily_minor": to_minor(a["spend_cap_daily"]),
            "max_per_transaction_minor": None if a.get("max_per_transaction") is None else to_minor(a["max_per_transaction"]),
            "action_limits_minor": {k: to_minor(v) for k, v in a.get("action_limits", {}).items()},
            "action_daily_caps_minor": {},
            "rate_limit_per_minute": a.get("rate_limit_per_minute"),
            "approval_threshold_minor": None if a.get("approval_threshold") is None else to_minor(a["approval_threshold"]),
            "redact_data_classes": a.get("redact_data_classes", []),
            "block_data_classes": a.get("block_data_classes", []),
        }
    return docs


def boundary_fields(schema: dict) -> dict[str, str]:
    props = schema["$defs"]["agent"]["properties"]
    return {name: spec["x-boundary"] for name, spec in props.items() if "x-boundary" in spec}


def cases_for(agent_id: str, agent: dict, fields: dict[str, str]) -> list[tuple[str, dict, tuple]]:
    out = []
    action = agent["allowed_actions"][0]
    targets: list[tuple[str, str, int]] = []
    for field, kind in fields.items():
        value = agent.get(field)
        if kind == "per_action":
            targets += [(f"per_action_{act}", act, lim) for act, lim in value.items() if act in agent["allowed_actions"]]
        elif value is not None and kind != "daily":  # daily cap is a counter limit, covered in the Lua parity test
            targets.append((kind, action, value))
    for label, act, limit in targets:
        for delta, tag in ((-1, "below"), (0, "at"), (1, "above")):
            amount = max(0, limit + delta)
            inp = {"agent_id": agent_id, "action": act, "amount_minor": amount}
            outcome, rule, _ = oracle(agent, inp)
            out.append((f"{agent_id}_{label}_{tag}", inp, (outcome, rule)))
    return out


def render(fields: dict[str, str]) -> str:
    agents = seed_agent_docs()
    lines = [
        "# GENERATED by scripts/gen_policy_tests.py from policies/data.schema.json. Do not edit by hand.",
        "# Boundary tests at limit-0.01 / limit / limit+0.01; expectations come from the Python oracle.",
        "package veyrqun.generated_boundaries_test",
        "",
        "import data.veyrqun.authz",
        "",
        f"agents := {json.dumps(agents, sort_keys=True)}",
        "",
    ]
    for agent_id, agent in agents.items():
        for name, inp, (outcome, rule) in cases_for(agent_id, agent, fields):
            rule_rego = "null" if rule is None else json.dumps(rule)
            lines += [
                f"test_{name} if {{",
                "\td := authz.decision with data.policy_data as {\"agents\": agents, \"fleet\": {\"stopped\": false}}",
                f"\t\twith input as {json.dumps(inp, sort_keys=True)}",
                f"\td.outcome == {json.dumps(outcome)}",
                f"\td.rule_id == {rule_rego}",
                "}",
                "",
            ]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    content = render(boundary_fields(json.loads(SCHEMA.read_text())))
    if args.check:
        if not OUT.exists() or OUT.read_text() != content:
            sys.exit("generated_boundaries_test.rego is stale; run: python scripts/gen_policy_tests.py")
        print("generated boundary tests up to date")
        return
    OUT.write_text(content)
    print(f"wrote {OUT.relative_to(ROOT)} ({content.count('test_')} tests)")


if __name__ == "__main__":
    main()
