"""Render the README results table from docs/results/*.json (the only allowed source of numbers).

  python scripts/render_results.py          # rewrites the block between the RESULTS markers in README.md
  python scripts/render_results.py --check  # CI: fail if the README is out of date with the JSON files

A metric whose file is missing renders as TBD.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "docs" / "results"
README = ROOT / "README.md"
START, END = "<!-- RESULTS:START (generated by scripts/render_results.py) -->", "<!-- RESULTS:END -->"


def load(name: str) -> dict | None:
    p = RESULTS / f"{name}.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def rows() -> list[tuple[str, str, str]]:
    out: list[tuple[str, str, str]] = []
    tbd = "TBD"

    g = load("gateway_latency")
    out.append(("Gateway overhead (inline policy, classification, limits)",
                f"p50 {g['gateway_overhead_ms']['med']} ms · p99 {g['gateway_overhead_ms']['p(99)']} ms "
                f"at {g['setup']['rate_rps_tool_calls'] + g['setup']['rate_rps_chat']} req/s, {g['requests']} requests"
                if g else tbd, "gateway_latency.json"))
    k = load("kill_switch")
    out.append(("Kill switch: operator action to first refused request",
                f"median {k['median_ms']} ms · max {k['max_ms']} ms" if k else tbd, "kill_switch.json"))
    e, b = load("guardrail_eval"), load("guardrail_eval_before")
    if e:
        before = f" (was {b['must_block']['detection_rate']:.1%} before the guardrail work)" if b else ""
        out.append(("Guardrails: attacks stopped (injection, card numbers, secrets, tool misuse)",
                    f"{e['must_block']['stopped']}/{e['must_block']['cases']} = {e['must_block']['detection_rate']:.1%}{before}",
                    "guardrail_eval.json"))
        out.append(("Guardrails: benign requests wrongly refused",
                    f"{e['benign']['false_positives']}/{e['benign']['cases']}", "guardrail_eval.json"))
    else:
        out.append(("Guardrail eval", tbd, "guardrail_eval.json"))
    gk = load("guardrail_eval_gke")
    if gk:
        out.append(("Same eval on the live GKE demo (Gemini 3.5 Flash behind the gateway)",
                    f"{gk['must_block']['stopped']}/{gk['must_block']['cases']} stopped · "
                    f"{gk['benign']['false_positives']}/{gk['benign']['cases']} false positives", "guardrail_eval_gke.json"))
    p = load("policy_parity")
    out.append(("Policy parity: compiled Rego vs Python reference, random inputs",
                f"{p['mismatches']} mismatches in {p['cases']:,}" if p else tbd, "policy_parity.json"))
    s = load("scenarios")
    if s:
        sm = s["summary"]
        out.append(("Agent fleet scenarios (LangGraph, incl. rogue agent and human approvals)",
                    f"{sm['passed']}/{sm['scenarios']} as specified · {sm['governed_calls_in_ledger']}/{sm['governed_calls']} "
                    "calls in a valid signed ledger", "scenarios.json"))
    d = load("gke_demo")
    out.append(("Public demo smoke test (visitor's path through GKE)",
                f"{d['checks_passed']}/{d['checks_total']} checks" if d else tbd, "gke_demo.json"))
    m = load("migration_validation")
    out.append(("Legacy SQLite to Postgres migration validation",
                f"{m['checks_total'] - m['checks_failed']}/{m['checks_total']} checks" if m else tbd,
                "migration_validation.json"))
    c = load("control_plane_latency")
    out.append(("Policy evaluation (WASM, in-process)",
                f"p50 {c['policy_eval_wasm_python']['p50_us']} µs · p99 {c['policy_eval_wasm_python']['p99_us']} µs"
                if c else tbd, "control_plane_latency.json"))
    z = load("zap_summary")
    if z:
        cp = z["targets"].get("localhost:8000", {}).get("by_risk", {})
        out.append(("OWASP ZAP API scan of the control plane",
                    f"High {cp.get('High', 0)} · Medium {cp.get('Medium', 0)} · Low {cp.get('Low', 0)}", "zap_summary.json"))
    return out


def render() -> str:
    lines = [START, "", "| What was measured | Result | Source |", "|---|---|---|"]
    lines += [f"| {a} | {b} | [`{c}`](docs/results/{c}) |" for a, b, c in rows()]
    return "\n".join(lines + ["", END])


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = README.read_text(encoding="utf-8")
    if START not in text or END not in text:
        sys.exit("README.md has no RESULTS markers")
    new = text[: text.index(START)] + render() + text[text.index(END) + len(END):]
    if a.check:
        if new != text:
            sys.exit("README results table is out of date: run python scripts/render_results.py")
        print("README results table is up to date")
        return
    README.write_text(new, encoding="utf-8")
    print(render())


if __name__ == "__main__":
    main()
